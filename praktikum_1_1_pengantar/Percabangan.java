//percabangan if-else
public class Percabangan {
    public static void main (String[] args) {
        int a = 4;
        if (a < 5) {
            System.out.println("Nilai a lebih kecil daripada 5");
        } else {
            System.out.println("Nilai a lebih besar daripada 5");
        }
    }
}
